export const OTHER = "שונות";
export const AISLE_ORDER = [...AISLES.map(([a]) => a), OTHER];

/** Keywords match at the start of a word (so "פיתות" is bread, not "תות"); the longest match wins ("שוקולד" over "שוקו"). */
export function aisleOf(name: string): string {
  const words = name.trim().split(/[\s,.\-/]+/).filter(Boolean);
  let best = OTHER, bestLen = 0;
  for (const [aisle, keys] of AISLES) {
    for (const k of keys) {
      if (k.length <= bestLen) continue;
      const first = k.split(" ")[0];
      const hit = k.includes(" ")
        ? words.some((w, i) => w.startsWith(first) && words.slice(i).join(" ").startsWith(k))
        : words.some((w) => w.startsWith(k));
      if (hit) { best = aisle; bestLen = k.length; }
    }
  }
  return best;
}
